import { ref } from 'vue'
export const currentLang = ref('zh')

export const t = (key) => {
  if (!key) return ''
  const lang = currentLang.value || 'zh'
  return i18n[lang][key] || key
}

export const toggleLang = () => {
  currentLang.value = currentLang.value === 'zh' ? 'en' : 'zh'
}
